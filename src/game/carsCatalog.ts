export function getCarSpec(carId: string): CarSpec {
  return CAR_CATALOG.find((c) => c.id === carId) ?? CAR_CATALOG[0];
}

export function createDefaultCustomization(car: CarSpec): CarCustomization {
  return {
    paintColor: car.defaultPaint,
    secondaryColor: car.defaultSecondary,
    wheelDesign: car.bodyStyle === 'muscle' ? 'deep_dish' : car.bodyStyle === 'hypercar' ? 'turbine' : 'mesh_gt',
    rimColor: car.bodyStyle === 'hypercar' ? '#18181b' : '#cbd5e1',
    spoiler: car.bodyStyle === 'hypercar' ? 'swan_neck' : car.bodyStyle === 'jdm' ? 'gt_wing' : 'lip',
    headlightStyle: car.bodyStyle === 'hypercar' ? 'ice_blue' : 'xenon_white',
    upgrades: {
      engine: 0,
      brakes: 0,
      handling: 0,
      nitro: 0,
    },
  };
}
